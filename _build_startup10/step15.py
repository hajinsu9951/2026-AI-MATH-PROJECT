def swap_tbody(html, lesson_id, new_tbody, table_index=0):
    start = html.find('id="' + lesson_id + '"')
    assert start > 0, lesson_id
    seg = html[start:]
    idx = 0
    pos = 0
    while True:
        t = seg.find('<table class="lp-table">', pos)
        assert t > 0, lesson_id + ' table'
        if idx == table_index:
            b1 = seg.find('<tbody>', t) + len('<tbody>')
            b2 = seg.find('</tbody>', b1)
            seg = seg[:b1] + '\n' + new_tbody + '\n            ' + seg[b2:]
            break
        idx += 1
        pos = t + 10
    return html[:start] + seg

def R(stage, act, mat):
    return ('              <tr><td class="td-c"><b>' + stage + '</b></td><td>' + act + '</td><td>' + mat + '</td></tr>')

